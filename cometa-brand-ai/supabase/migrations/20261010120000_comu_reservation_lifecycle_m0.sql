-- Buyer writes must use the lifecycle RPCs. Row ownership alone did not stop
-- an owner from changing COMMITTED to CANCELLED without releasing inventory.
revoke insert,update,delete on public.comu_inventory_reservations,public.comu_inventory_reservation_items from public,anon,authenticated;
drop policy comu_reservations_buyer on public.comu_inventory_reservations;
create policy comu_reservations_buyer on public.comu_inventory_reservations for select to authenticated
  using (buyer_id is not distinct from (select id from public.comu_buyers where user_id=auth.uid()) or public.is_cometa_admin());
-- M0 serializes lifecycle commands by reservation before locking order/payment/
-- inventory rows. Existing pricing, snapshots, payment economics and O1/N1
-- triggers remain in the existing implementations, inaccessible to clients.
alter function public.comu_reserve_inventory(uuid,text,text,jsonb) rename to comu_m0_reserve_impl;
