revoke all on function public.comu_m0_reserve_impl(uuid,text,text,jsonb), public.comu_m0_order_impl(uuid,text,jsonb,text), public.comu_m0_payment_impl(text,bigint,text,text,jsonb) from public,anon,authenticated,service_role;

create function public.comu_m0_items(p_items jsonb) returns jsonb
language sql immutable set search_path=public as $$
  select coalesce(jsonb_agg(x order by x::text),'[]'::jsonb) from (
    select jsonb_build_object('seller_id',(v->>'seller_id')::uuid,
      'listing_id',(v->>'listing_id')::uuid,'variant_listing_id',(v->>'variant_listing_id')::uuid,
      'variant_id',(v->>'variant_id')::uuid,'location_id',(v->>'location_id')::uuid,
      'quantity',(v->>'quantity')::numeric,'pricing_snapshot',v->'pricing_snapshot') x
    from jsonb_array_elements(p_items) v
  ) s
$$;

create function public.comu_reserve_inventory(p_buyer_id uuid,p_session_key text,p_idempotency_key text,p_items jsonb)
returns public.comu_inventory_reservations language plpgsql security definer set search_path=public as $$
declare r public.comu_inventory_reservations%rowtype; stored jsonb; canonical jsonb; ordered jsonb;
begin
  if p_buyer_id is null or (auth.uid() is not null and p_buyer_id is distinct from (select id from public.comu_buyers where user_id=auth.uid())) then raise exception 'COMU_UNAUTHORIZED'; end if;
  if p_idempotency_key is null or btrim(p_idempotency_key)='' then raise exception 'COMU_IDEMPOTENCY_REQUIRED'; end if;
  if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception 'COMU_RESERVATION_ITEMS_REQUIRED'; end if;
  canonical:=public.comu_m0_items(p_items);
  perform pg_advisory_xact_lock(hashtextextended('comu:m0:reserve-key:'||p_idempotency_key,0));
  select * into r from public.comu_inventory_reservations where idempotency_key=p_idempotency_key;
  if found then
    if r.buyer_id is distinct from p_buyer_id then raise exception 'COMU_IDEMPOTENCY_CONFLICT'; end if;
    select public.comu_m0_items(coalesce(jsonb_agg(to_jsonb(i)),'[]')) into stored from public.comu_inventory_reservation_items i where reservation_id=r.id;
    if stored is distinct from canonical then raise exception 'COMU_IDEMPOTENCY_CONFLICT'; end if;
    return r;
  end if;
  -- Session key is a transport nonce, regenerated by the existing TS caller;
  -- it is deliberately not part of the semantic request identity.
  select jsonb_agg(v order by v->>'location_id',v->>'variant_id',v::text) into ordered from jsonb_array_elements(p_items) v;
  return public.comu_m0_reserve_impl(p_buyer_id,p_session_key,p_idempotency_key,ordered);
end $$;

create function public.comu_create_order_from_reservation(p_reservation_id uuid,p_idempotency_key text,p_shipping_address_snapshot jsonb,p_currency text default 'MXN')
returns public.comu_orders language plpgsql security definer set search_path=public as $$
declare r public.comu_inventory_reservations%rowtype; o public.comu_orders%rowtype;
begin
  select * into r from public.comu_inventory_reservations where id=p_reservation_id;
  if not found or (auth.uid() is not null and r.buyer_id is distinct from (select id from public.comu_buyers where user_id=auth.uid())) then raise exception 'COMU_RESERVATION_NOT_FOUND'; end if;
  if p_idempotency_key is null or btrim(p_idempotency_key)='' then raise exception 'COMU_IDEMPOTENCY_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtextextended('comu:m0:order-key:'||p_idempotency_key,0));
  select * into o from public.comu_orders where idempotency_key=p_idempotency_key;
  if found then
    if o.buyer_id is distinct from r.buyer_id or o.reservation_id is distinct from r.id or o.currency is distinct from p_currency or o.shipping_address_snapshot is distinct from p_shipping_address_snapshot then raise exception 'COMU_IDEMPOTENCY_CONFLICT'; end if;
    return o;
  end if;
  perform pg_advisory_xact_lock(hashtextextended('comu:m0:reservation:'||r.id,0));
  if exists(select 1 from public.comu_orders where reservation_id=r.id) then raise exception 'COMU_IDEMPOTENCY_CONFLICT'; end if;
  return public.comu_m0_order_impl(p_reservation_id,p_idempotency_key,p_shipping_address_snapshot,p_currency);
end $$;

-- Private primitive. Terminal/paid reservations are never subtracted again.
create function public.comu_m0_release(p_id uuid,p_target text) returns public.comu_inventory_reservations
language plpgsql security definer set search_path=public as $$
declare r public.comu_inventory_reservations%rowtype; o public.comu_orders%rowtype; i record;
begin
  if p_target not in ('RELEASED','CANCELLED','EXPIRED') then raise exception 'COMU_RESERVATION_STATUS_INVALID'; end if;
  perform pg_advisory_xact_lock(hashtextextended('comu:m0:reservation:'||p_id,0));
  if (select count(*) from public.comu_orders where reservation_id=p_id)>1 then raise exception 'COMU_RESERVATION_ORDER_CONFLICT'; end if;
  select * into o from public.comu_orders where reservation_id=p_id for update;
  perform 1 from public.comu_payment_intents where order_id=o.id order by id for update;
  select * into r from public.comu_inventory_reservations where id=p_id for update;
  if not found then raise exception 'COMU_RESERVATION_NOT_FOUND'; end if;
  if r.status in ('RELEASED','CANCELLED','EXPIRED') then return r; end if;
  if p_target='EXPIRED' and r.expires_at>clock_timestamp() then return r; end if;
  if exists(select 1 from public.comu_inventory_commit_items where reservation_id=r.id)
    or exists(select 1 from public.comu_payment_intents where order_id=o.id and status in ('SUCCEEDED','REFUNDED','PARTIALLY_REFUNDED'))
    or (o.id is not null and o.status not in ('PAYMENT_PENDING','CANCELLED','EXPIRED')) then
    if p_target='EXPIRED' then return r; end if;
    raise exception 'COMU_ORDER_NOT_CANCELLABLE';
  end if;
  -- A committed reservation without its order is inconsistent; don't guess.
  if r.status='COMMITTED' and o.id is null then raise exception 'COMU_RESERVATION_ORDER_CONFLICT'; end if;
  for i in select variant_id,location_id,sum(quantity) quantity from public.comu_inventory_reservation_items
    where reservation_id=r.id group by location_id,variant_id order by location_id,variant_id loop
    perform 1 from public.pos_inventory where location_id=i.location_id and variant_id=i.variant_id for update;
    update public.pos_inventory set reserved_quantity=reserved_quantity-i.quantity,updated_at=now()
      where location_id=i.location_id and variant_id=i.variant_id and reserved_quantity>=i.quantity;
    if not found then raise exception 'COMU_RESERVATION_STOCK_CONFLICT'; end if;
  end loop;
  update public.comu_inventory_reservations set status=p_target,released_at=now(),updated_at=now(),cancelled_at=case when p_target='CANCELLED' then now() else cancelled_at end where id=r.id returning * into r;
  if o.id is not null and o.status='PAYMENT_PENDING' then
    update public.comu_orders set status=case when p_target='EXPIRED' then 'EXPIRED' else 'CANCELLED' end,
      cancelled_at=case when p_target='EXPIRED' then cancelled_at else now() end,updated_at=now() where id=o.id;
    update public.comu_order_suborders set status='CANCELLED',cancelled_at=now(),updated_at=now() where order_id=o.id;
    insert into public.comu_order_events(order_id,event_type,actor_type,payload)
      values(o.id,case when p_target='EXPIRED' then 'ORDER_EXPIRED' else 'ORDER_CANCELLED' end,'SYSTEM',jsonb_build_object('reservationId',r.id));
  end if;
  insert into public.comu_order_events(order_id,event_type,actor_type,payload)
    values(o.id,case when p_target='EXPIRED' then 'RESERVATION_EXPIRED' else 'RESERVATION_RELEASED' end,'SYSTEM',jsonb_build_object('reservationId',r.id));
  return r;
end $$;

create or replace function public.comu_release_inventory_reservation(p_reservation_id uuid,p_status text default 'RELEASED')
returns public.comu_inventory_reservations language plpgsql security definer set search_path=public as $$
declare r public.comu_inventory_reservations%rowtype;
begin
  select * into r from public.comu_inventory_reservations where id=p_reservation_id;
  if not found or (auth.uid() is not null and r.buyer_id is distinct from (select id from public.comu_buyers where user_id=auth.uid()) and not public.is_cometa_admin()) then raise exception 'COMU_RESERVATION_NOT_FOUND'; end if;
  if p_status not in ('RELEASED','CANCELLED') then raise exception 'COMU_RESERVATION_STATUS_INVALID'; end if;
  return public.comu_m0_release(p_reservation_id,p_status);
end $$;

create or replace function public.comu_cancel_order(p_order_id uuid) returns public.comu_orders
language plpgsql security definer set search_path=public as $$
declare o public.comu_orders%rowtype;
begin
  select o1.* into o from public.comu_orders o1 join public.comu_buyers b on b.id=o1.buyer_id
    where o1.id=p_order_id and (auth.uid() is null or b.user_id=auth.uid() or public.is_cometa_admin());
  if not found then raise exception 'COMU_ORDER_NOT_FOUND'; end if;
  perform pg_advisory_xact_lock(hashtextextended('comu:m0:reservation:'||o.reservation_id,0));
  select * into o from public.comu_orders where id=p_order_id for update;
  if o.status='CANCELLED' then return o; end if;
  if o.status<>'PAYMENT_PENDING' then raise exception 'COMU_ORDER_NOT_CANCELLABLE'; end if;
  perform public.comu_m0_release(o.reservation_id,'CANCELLED');
  select * into o from public.comu_orders where id=p_order_id;
  return o;
end $$;

create or replace function public.comu_expire_inventory_reservations() returns integer
language plpgsql security definer set search_path=public as $$
declare candidate record; r public.comu_inventory_reservations%rowtype; n integer:=0;
begin
  for candidate in select id from public.comu_inventory_reservations where status in ('ACTIVE','COMMITTED') and expires_at<=clock_timestamp() order by id loop
    -- Skip a lifecycle command already in flight instead of locking out checkout.
    if not pg_try_advisory_xact_lock(hashtextextended('comu:m0:reservation:'||candidate.id,0)) then continue; end if;
    select * into r from public.comu_inventory_reservations where id=candidate.id;
    if r.status not in ('ACTIVE','COMMITTED') then continue; end if;
    r:=public.comu_m0_release(candidate.id,'EXPIRED');
    if r.status='EXPIRED' then n:=n+1; end if;
  end loop;
  return n;
end $$;

create function public.comu_mark_payment_succeeded(p_stripe_payment_intent_id text,p_amount_cents bigint,p_currency text,p_event_id text default null,p_payload jsonb default '{}'::jsonb)
returns public.comu_payment_intents language plpgsql security definer set search_path=public as $$
declare p public.comu_payment_intents%rowtype; o public.comu_orders%rowtype; i record;
begin
  select * into p from public.comu_payment_intents where stripe_payment_intent_id=p_stripe_payment_intent_id;
  if not found then raise exception 'COMU_PAYMENT_NOT_FOUND'; end if;
  select * into o from public.comu_orders where id=p.order_id;
  perform pg_advisory_xact_lock(hashtextextended('comu:m0:reservation:'||o.reservation_id,0));
  perform 1 from public.comu_orders where id=o.id for update;
  select * into p from public.comu_payment_intents where id=p.id for update;
  if p.amount_cents is distinct from p_amount_cents or p.currency is distinct from upper(p_currency) then raise exception 'COMU_PAYMENT_AMOUNT_CURRENCY_MISMATCH'; end if;
  -- Deadline is checked after waiting, not at transaction start. Paid/committed
  -- inventory is protected by comu_m0_release and is never freed here.
  perform public.comu_m0_release(o.reservation_id,'EXPIRED');
  for i in select distinct location_id,variant_id from public.comu_inventory_reservation_items where reservation_id=o.reservation_id order by location_id,variant_id loop
    perform 1 from public.pos_inventory where location_id=i.location_id and variant_id=i.variant_id for update;
  end loop;
  p:=public.comu_m0_payment_impl(p_stripe_payment_intent_id,p_amount_cents,p_currency,p_event_id,p_payload);
  return p;
end $$;

