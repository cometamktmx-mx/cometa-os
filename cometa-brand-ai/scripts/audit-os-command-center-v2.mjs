import fs from "node:fs";
import path from "node:path";
const root = process.cwd();
const file = (p) => path.join(root, p);
const exists = (p) => fs.existsSync(file(p));
const read = (p) => fs.readFileSync(file(p), "utf8");
const checks = [];
function check(name, ok) { checks.push(ok); console.log(`${ok ? "PASS" : "FAIL"} ${name}`); }
const route = "src/app/api/os/[brandSlug]/command-center/route.ts";
const page = "src/app/brand/[brandSlug]/os/page.tsx";
const api = read(route);
const client = read("src/app/brand/[brandSlug]/os/components/command-center-client.tsx");
check("canonical brand guard", api.includes("requireBrandOsAccess"));
check("service role after authorization", api.indexOf("requireBrandOsAccess") < api.indexOf("admin()"));
check("real Sales sources", api.includes("sales_leads") && api.includes("sales_followups"));
check("real Marketing sources", api.includes("mercury_content_items") && api.includes("strategy_publications"));
check("persisted evidence only", !api.includes("openai") && !client.includes("generate"));
check("no AI calls on page load", !client.includes("/api/ai") && !client.includes("openai"));
check("no fake connections", !api.includes("Meta Ads") && !api.includes("Shopify"));
check("POS optional", api.includes("pos_subscriptions"));
check("no POS operational duplication", !page.includes("usePosContext"));
check("no internal Mercury data exposed", !client.includes("assignments") && !client.includes("team workload"));
check("no fake attribution", !client.includes("revenue attributed") && !client.includes("ROAS"));
check("partial failure UI", client.includes("ErrorState"));
check("canonical Intelligence CTA", exists("src/app/brand/[brandSlug]/os/intelligence/page.tsx"));
check("canonical Sales CTA", client.includes("sales"));
check("mobile-ready layout", client.includes("sm:grid-cols") && client.includes("grid"));
check("legacy routes absent from home", !page.includes("/workspace") && !page.includes("/mission-control"));
const failed = checks.filter((x) => !x).length;
console.log(JSON.stringify({ total: checks.length, passed: checks.length - failed, failed, allChecksPassed: failed === 0 }));
process.exitCode = failed ? 1 : 0;
